const fs=require('node:fs'),sharp=require('sharp');
const dir='assets/ui/wardrobe/accessories';
function components(data,w,h,test){
 const seen=new Uint8Array(w*h),queue=new Int32Array(w*h),result=[];
 for(let start=0;start<w*h;start++){
  if(seen[start]||!test(data[start*4+3]))continue;
  let read=0,length=1;queue[0]=start;seen[start]=1;
  let count=0,minX=w,minY=h,maxX=0,maxY=0,sumX=0,sumY=0,edge=false;
  while(read<length){const p=queue[read++],x=p%w,y=Math.floor(p/w);count++;sumX+=x;sumY+=y;minX=Math.min(minX,x);maxX=Math.max(maxX,x);minY=Math.min(minY,y);maxY=Math.max(maxY,y);if(!x||!y||x===w-1||y===h-1)edge=true;
   for(const q of [x?p-1:-1,x<w-1?p+1:-1,y?p-w:-1,y<h-1?p+w:-1])if(q>=0&&!seen[q]&&test(data[q*4+3])){seen[q]=1;queue[length++]=q}
  }
  result.push({count,minX,minY,maxX,maxY,cx:sumX/count,cy:sumY/count,edge});
 }
 return result.sort((a,b)=>b.count-a.count);
}
(async()=>{
 const socket=await sharp('assets/ui/slime/slime-eye-sockets-reference-v1.webp').ensureAlpha().raw().toBuffer({resolveWithObject:true});
 const eyes=components(socket.data,socket.info.width,socket.info.height,a=>a>100).filter(c=>c.count>1000).slice(0,2).sort((a,b)=>a.cx-b.cx);
 const factor=2.36*.74/socket.info.width;
 const targetSpan=(eyes[1].cx-eyes[0].cx)*factor,targetY=((eyes[0].cy+eyes[1].cy)/2-socket.info.height/2)*factor;
 const manifest={},analysis={targetSpan,targetY,items:{}};
 for(const id of ['round','mask','moustache','visor','stars','blindfold']){
  const variant=['round','mask','stars'].includes(id)?'v2':'v1';
  const source=`${dir}/${id}-${variant}-master.png`;
  const raw=await sharp(source).ensureAlpha().raw().toBuffer({resolveWithObject:true}),{width:w,height:h}=raw.info;
  const shapes=components(raw.data,w,h,a=>a>40),big=shapes.filter(c=>c.count>=shapes[0].count*.005);
  const minX=Math.min(...big.map(c=>c.minX)),minY=Math.min(...big.map(c=>c.minY)),maxX=Math.max(...big.map(c=>c.maxX)),maxY=Math.max(...big.map(c=>c.maxY));
  const pad=3,left=Math.max(0,minX-pad),top=Math.max(0,minY-pad),width=Math.min(w-left,maxX-minX+1+pad*2),height=Math.min(h-top,maxY-minY+1+pad*2);
  const outWidth=768,ratio=outWidth/width,image=`${dir}/${id}-v1.webp`;
  const info=await sharp(source).extract({left,top,width,height}).resize({width:outWidth}).webp({quality:92,alphaQuality:100}).toFile(image);
  const fit={image,pixelWidth:info.width,pixelHeight:info.height,anchorX:info.width*.5,anchorY:info.height*.5,targetY};
  const holes=components(raw.data,w,h,a=>a<48).filter(c=>!c.edge&&c.count>400).slice(0,2).sort((a,b)=>a.cx-b.cx);
  if(['round','mask','stars'].includes(id)){
   if(holes.length!==2)throw new Error(`Expected two clear openings in ${id}`);
   fit.anchorX=((holes[0].cx+holes[1].cx)/2-left)*ratio;fit.anchorY=((holes[0].cy+holes[1].cy)/2-top)*ratio;
   fit.span=Math.hypot(holes[1].cx-holes[0].cx,holes[1].cy-holes[0].cy)*ratio;fit.targetSpan=targetSpan;
   fit.rotation=-Math.atan2(holes[1].cy-holes[0].cy,holes[1].cx-holes[0].cx);
   fit.opening=id==='mask' ? .56 : id==='stars' ? .50 : .55;
   fit.holes=holes.map(hole=>({x:(hole.cx-left)*ratio,y:(hole.cy-top)*ratio,size:Math.min(hole.maxX-hole.minX+1,hole.maxY-hole.minY+1)*ratio}));
  }else if(id==='moustache'){fit.width=1.30;fit.targetY=.39;fit.coversMouth=true;}
  else if(id==='visor'){fit.width=1.84;fit.coversEyes=true;}
  else if(id==='blindfold'){fit.width=2.12;fit.coversEyes=true;fit.anchorX=info.width*.57;fit.anchorY=info.height*.43;}
  manifest[id]=fit;analysis.items[id]={source,sourceSize:[w,h],crop:{left,top,width,height},holes,fit};
 }
 fs.writeFileSync('js/config/accessory-fit.js','// Generated by tools/export_accessories_689.cjs. Face-relative fitted raster accessories.\nwindow.SlimeAccessoryFit = Object.freeze('+JSON.stringify(manifest,null,2)+');\n');
 fs.writeFileSync('outputs/accessories-689/fitting-analysis.json',JSON.stringify(analysis,null,2));
 console.log(JSON.stringify(analysis,null,2));
})().catch(e=>{console.error(e);process.exitCode=1});
