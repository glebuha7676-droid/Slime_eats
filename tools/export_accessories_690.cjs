const fs=require('fs'),vm=require('vm'),sharp=require('sharp');
const original=fs.readFileSync('tools/export_accessories_689.cjs','utf8');
const components=new Function(original.slice(original.indexOf('function components'),original.indexOf('(async()=>'))+';return components;')();
(async()=>{
 const box={window:{}};vm.runInNewContext(fs.readFileSync('js/config/accessory-fit.js','utf8'),box);const fits={...box.window.SlimeAccessoryFit};
 const analysis={};
 for(const id of ['round','mask','stars','aviator']){
  const source=`assets/ui/wardrobe/accessories/${id}-${id==='stars'?'v4':'v3'}-master.png`;
  const raw=await sharp(source).ensureAlpha().raw().toBuffer({resolveWithObject:true}),{width:w,height:h}=raw.info;
  const shapes=components(raw.data,w,h,a=>a>40),big=shapes.filter(c=>c.count>=shapes[0].count*.005);
  const left=Math.max(0,Math.min(...big.map(c=>c.minX))-3),top=Math.max(0,Math.min(...big.map(c=>c.minY))-3),right=Math.min(w,Math.max(...big.map(c=>c.maxX))+4),bottom=Math.min(h,Math.max(...big.map(c=>c.maxY))+4);
  const width=right-left,height=bottom-top,ratio=768/width,image=`assets/ui/wardrobe/accessories/${id}-v2.webp`;
  const info=await sharp(source).extract({left,top,width,height}).resize({width:768}).webp({quality:92,alphaQuality:100}).toFile(image);
  const holes=components(raw.data,w,h,a=>a<48).filter(c=>!c.edge&&c.count>400).slice(0,2).sort((a,b)=>a.cx-b.cx);
  if(holes.length!==2)throw new Error('Missing lens opening '+id);
  const fit={image,pixelWidth:info.width,pixelHeight:info.height,anchorX:((holes[0].cx+holes[1].cx)/2-left)*ratio,anchorY:((holes[0].cy+holes[1].cy)/2-top)*ratio,targetY:.0231437,span:Math.hypot(holes[1].cx-holes[0].cx,holes[1].cy-holes[0].cy)*ratio,targetSpan:.6496428,rotation:-Math.atan2(holes[1].cy-holes[0].cy,holes[1].cx-holes[0].cx)};
  if(id==='round')fit.magnification=1.12;
  if(id==='stars')fit.magnification=.80;
  fits[id]=fit;analysis[id]={holes,crop:{left,top,width,height},fit};
 }
 fs.writeFileSync('js/config/accessory-fit.js','// Generated by tools/export_accessories_690.cjs. Whole-sprite fitting in face coordinates.\nwindow.SlimeAccessoryFit=Object.freeze('+JSON.stringify(fits,null,2)+');\n');
 const source='assets/ui/wardrobe/cosmetic-cylinder-v1-master.png';
 await sharp(source).trim().resize({width:420}).webp({quality:90,alphaQuality:100}).toFile('assets/ui/wardrobe/cosmetic-cylinder-v1.webp');
 fs.writeFileSync('outputs/wardrobe-690/fitting.json',JSON.stringify(analysis,null,2));
 console.log(Object.fromEntries(Object.entries(analysis).map(([id,v])=>[id,v.fit])));
})().catch(e=>{console.error(e);process.exitCode=1});
