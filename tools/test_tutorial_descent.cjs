const assert=require('node:assert/strict'),fs=require('node:fs');
const ordinary=require('../js/generation/world1-descent.js'),tutorial=require('../js/generation/tutorial-descent.js');
for(let sample=0;sample<100;sample++){
 const original=ordinary.build(),before=JSON.stringify(original);
 const first=tutorial.build({phase:1,normal:original});
 assert.equal(first.rows,74);
 assert(first.cells.flat().every(c=>!c.hazard&&!c.special&&!c.flaskTier),'First run only teaches controls and ability');
 assert(new Set(first.cells.flat().map(c=>c.tier)).size>=3);
 assert(new Set(first.cells.map(row=>row.map(c=>c.tier).join(','))).size>12,'No uniform rock stripes');
 const unchanged=first.cells.flatMap((row,y)=>row.map((c,x)=>c.tier===original.cells[y][x].tier)).filter(Boolean).length;
 assert(unchanged>first.rows*6*.6);
 const originalSection=original.cells.slice(0,first.rows).flat();
 assert(first.cells.flat().filter(c=>c.dead).length<=originalSection.filter(c=>c.dead).length);
 for(let row=1;row<first.rows;row++)assert.equal(first.cells[row][first.guideCols[row]].tier,'dense','Keep the fragile guiding route');
 const second=tutorial.build({phase:2,normal:original});
 assert.equal(second.rows,74);
 assert(second.cells[second.firstHazard.row][second.firstHazard.col].hazard);
 assert(second.cells.slice(0,tutorial.HAZARD.row).flat().every(c=>!c.hazard));
 assert(second.cells.slice(0,tutorial.VEIN.row).flat().every(c=>!c.flaskTier));
 assert.equal(second.cells.flat().filter(c=>c.special==='gel').length,1);
 assert.equal(second.cells.flat().filter(c=>c.hazard).length,1);
 assert(second.heal.row>second.firstHazard.row+12);
 assert(second.firstVein.row>second.heal.row+12);
 assert.equal(second.cells.flat().filter(c=>c.flaskTier).length,18);
 assert.equal(second.cells.flat().reduce((sum,c)=>sum+[0,1,3,5][c.flaskTier],0),80);
 assert.equal(second.cells.reduce((sum,row,y)=>sum+[0,1,3,5][row[second.guideCols[y]].flaskTier],0),60);
 const hazard=second.firstHazard;
 assert([hazard.col-1,hazard.col+1].some(x=>x>=0&&x<6&&[hazard.row-1,hazard.row,hazard.row+1].every(y=>second.cells[y][x].tier==='dense'&&!second.cells[y][x].hazard)),'Connected fragile bypass');
 for(const row of second.cells)assert(row.filter(c=>!c.hazard).length>=2);
 assert.equal(JSON.stringify(original),before);
}
const source=fs.readFileSync(require.resolve('../game.js'),'utf8');
const director=source.slice(source.indexOf('  function updateTutorialRun('),source.indexOf('  function finishOnboardingRun('));
assert(!/cameraY\s*=|pauseRun\(|tutorialPace\s*=/.test(director));
assert(director.includes('lessonTime>=25000'));
assert(director.includes('waitMs:1300'));
assert(director.includes("!$('#tutorialRunGoal').hidden")||source.includes('run.tutorialGoalAvailable'));
assert(!director.includes("setTutorialRunHint('fire'"));
console.log('100 ordinary mine variants, fragile routes, single heart below spikes, sparse ore and separated lessons passed.');
