"""Pack the visible alpha masks of laboratory dishes for local-file play."""
import base64
import json
from pathlib import Path
import subprocess

from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
SIZE = 64
catalog = subprocess.check_output(
    [
        "node", "-e",
        """
        const fs = require('node:fs');
        const vm = require('node:vm');
        const context = {window: {}};
        for (const file of ['js/config/image-paths.js', 'food-catalog.js', 'js/config/food-ground-bounds.js']) {
          vm.runInNewContext(fs.readFileSync(file, 'utf8'), context);
        }
        const {SLIME_FOOD_CATALOG, SlimeAssetPaths, SlimeFoodGroundBounds} = context.window;
        const dishes = SLIME_FOOD_CATALOG.map(food => [
          SlimeAssetPaths.resolve(food.image), SlimeFoodGroundBounds[food.id]
        ]);
        process.stdout.write(JSON.stringify(dishes));
        """,
    ],
    cwd=ROOT,
).decode("utf-8")

shapes = {}
for source, bounds in json.loads(catalog):
    with Image.open(ROOT / source) as art:
        alpha = art.convert("RGBA").getchannel("A")
        if bounds:
            width, height, left, top, right, bottom = bounds
            crop = (left * art.width / width, top * art.height / height,
                    right * art.width / width, bottom * art.height / height)
        else:
            crop = (0, 0, art.width, art.height)
        mask = alpha.transform((SIZE, SIZE), Image.Transform.EXTENT, crop, Image.Resampling.BICUBIC)
    bits = bytearray(SIZE * SIZE // 8)
    for index, opacity in enumerate(mask.tobytes()):
        if opacity >= 96:
            bits[index // 8] |= 1 << (index % 8)
    shapes[source] = base64.b64encode(bits).decode("ascii")

output = ROOT / "js/config/lab-food-shapes.js"
output.write_text(
    "// Generated by tools/prepare_lab_food_shapes.py from the packaged food art.\n"
    "window.SlimeLabFoodShapes = Object.freeze({\n"
    f"  size: {SIZE},\n  masks: "
    + json.dumps(shapes, ensure_ascii=False, indent=2).replace("\n", "\n  ")
    + "\n});\n",
    encoding="utf-8",
)
