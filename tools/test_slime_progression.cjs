const assert = require('node:assert/strict');
const fs = require('node:fs'), vm = require('node:vm');
const context = { window: {} };
vm.runInNewContext(fs.readFileSync(require.resolve('../js/config/slime-progression.js'), 'utf8'), context);
const P = context.window.SlimeProgression;
assert.equal(P.progress(1, 499).ready, false);
assert.equal(P.progress(1, 500).ready, true);
assert.equal(P.progress(1, 900).stage, 1, 'XP readiness never purchases an evolution automatically');
assert.equal(P.canEvolve(1, 500, 49), false, 'Both personal experience and plasma are required');
assert.equal(P.canEvolve(1, 499, 10000), false, 'Plasma cannot bypass experience');
assert.equal(P.canEvolve(1, 500, 50), true);
assert.equal(P.canEvolve(2, 1999, 100), false);
assert.equal(P.canEvolve(2, 2000, 100), true);
assert.equal(P.canEvolve(3, 100000, 100000), false, 'Stage III is the last evolution');
assert.equal(P.progress(2, 1250).percent, 50);
assert.equal(P.progress(1, Infinity).xp, 0);
const migrated = P.migrateExperience({fire: 2700}, ['fire', 'frost', 'phantom'], {fire: 3, frost: 2, phantom: 1});
assert.equal(migrated.fire, 2700);
assert.equal(migrated.frost, 500, 'Already bought evolutions retain their experience requirement');
assert.equal(migrated.phantom, 0, 'Unused slimes do not receive legacy global experience');
const save = { unlockedMutations: ['fire','frost'], mutationExperience: {fire: 480,frost: 7}, selectedMutation: 'frost' };
assert.equal(P.credit(save, 'fire', 40).after, 520);
assert.equal(save.mutationExperience.frost, 7, 'Rewards go to the played character, even if selection changed');
assert.equal(P.credit(save, 'locked', 999), null);
assert.equal(save.mutationExperience.fire, 520, 'Preparing an evolution does not spend experience');
console.log('Personal progression: XP + plasma gates, fixed stages, legacy evolutions, independent reward ownership and maximum stage passed');
